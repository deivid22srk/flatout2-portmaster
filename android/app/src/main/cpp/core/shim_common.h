// core/shim_common.h — shared state and helpers for the FlatOut 2 ARM64 guest on Android.
//
// The recompiled guest (fo2.aarch64) is a glibc Linux ET_EXEC binary. This library loads it
// into the app's own process (no exec(), no separate glibc) and satisfies its imports:
//   * glibc symbols  -> thin shims on top of bionic / raw syscalls (see shim/glibc_shim*.cpp)
//   * SDL2 symbols   -> our own mini-SDL2 backed by ANativeWindow/EGL/OpenSL ES (shim/sdl2_*.cpp)
//   * GLES2 symbols  -> forwarded to the system libGLESv2 (dlsym)
// Guest threads run with TPIDR_EL0 pointing at a glibc-layout TCB (see core/guest_thread.cpp);
// every shim that calls into bionic switches TPIDR to the thread's real bionic TCB first.
#pragma once

#include <cstddef>
#include <cstdint>

#include <string>
#include <vector>

namespace fo2 {

// --- /proc/self/maps helpers (shared by the ELF loader and the flat-window shims) ---

struct SelfMapsEntry {
    uint64_t start = 0, end = 0;
    std::string perms;              // e.g. "rw-p" or "---p"
    std::string path;               // empty for plain anonymous mappings
    unsigned long long inode = 0;
};

bool read_self_maps(std::vector<SelfMapsEntry>* out);

// Logs every mapping that overlaps [start, end), prefixed with `why`.
void log_overlapping_maps(uint64_t start, uint64_t end, const char* why);

// Unmaps every mapping overlapping [start, end) that is an unused reservation
// (PROT_NONE, anonymous, unnamed). Dropping those cannot break anything that
// already runs — they only exist to reserve address space. Returns how many
// were dropped.
int drop_pure_gap_maps(uint64_t start, uint64_t end);

// Guest thread TCB: glibc aarch64 layout (tcbhead_t) followed by our private metadata.
// The exe's TLS block sits immediately BEFORE this struct (tp-relative negative offsets).
struct GuestTcb {
    void*     tcb;              // +0x00 points to itself
    void*     dtv;              // +0x08 (unused: no DYNAMIC TLS relocs in the guest)
    void*     self;             // +0x10
    int32_t   multiple_threads; // +0x18
    int32_t   gscope_flag;      // +0x1c
    uint64_t  sysinfo;          // +0x20
    uint64_t  stack_guard;      // +0x28 (stack canary)
    uint64_t  pointer_guard;    // +0x30
    // --- glibc's pthread struct would continue here; guest never reads it directly. ---
    uint64_t  reserved[17];     // +0x38..0xBF pad (reserved[0] = kTcbMagic)
    void*     bionic_tp;        // +0xC0 the thread's REAL bionic TPIDR value
    void*     bionic_pthread;   // +0xC8 bionic pthread handle (for join/detach)
    void*     owner;            // +0xD0 GuestThreadCtx* (audio pump bookkeeping etc.)
};
static_assert(offsetof(GuestTcb, bionic_tp) == 0xC0, "asm thunk layout depends on this");
static_assert(offsetof(GuestTcb, bionic_pthread) == 0xC8, "asm thunk layout depends on this");

// Magic in reserved[0]: lets BionicGuard tell our TCBs from real bionic TCBs.
constexpr uint64_t kTcbMagic = 0x464F324755455354ULL; // "FO2GUEST"

// Offset used by the generated asm thunks (shim/auto_thunks.S) to find the bionic TP.
// TCB scratch beyond the struct: +0xD8 saved LR, +0xE0 saved x19 (see auto_thunks.S).
constexpr int kOffBionicTp = 0xC0;

// Logging with the FO2 tag: adb logcat -s FO2
void logi(const char* fmt, ...) __attribute__((format(printf, 1, 2)));
void loge(const char* fmt, ...) __attribute__((format(printf, 1, 2)));

// --- guest symbol resolution -------------------------------------------------
// Symbol classes are owned by the generated header shim/auto_imports.h
// (generated by cpp/gen_imports.py from the real fo2.aarch64 import list).

// Returns the address to write into the guest GOT for `name`, or nullptr.
// Order: static table (auto_imports.cpp) -> dlsym(DlSym class) -> weak -> error.
void* find_guest_symbol(const char* name);

// --- flat guest address space -------------------------------------------------
// GuestMemory (inside the guest) reserves 64 GiB of host address space and
// requires it to land at the EXACT base 0x100000000: the recompiled game
// hardcodes (0x100000000 | guest_va) in every memory access. Prepares the span
// before the guest starts (drops unused reservations, reports real blockers).
void flat_memory_prepare();

// --- lifecycle ---------------------------------------------------------------
// Loads the guest ELF and starts it on a fresh guest thread. Returns false on failure.
bool guest_start(const char* binPath, const char* gameDir, int renderW, int renderH, int capFps);
void guest_request_stop();
bool guest_is_running();

// Surface lifecycle (JNI thread context; bionic TPIDR valid here).
void video_set_surface(void* anativeWindow);   // ANativeWindow*
void video_clear_surface();
void video_set_paused(bool paused);

// Input injection (called from bionic threads).
void input_set_axis(int axis, float value);     // 0..5 = LX,LY,RX,RY,LT,RT
void input_set_button(int button, bool down);   // SDL_GameControllerButton codes

} // namespace fo2
